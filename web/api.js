export class ApiError extends Error {
  constructor(message, status, detail) { super(message); this.name='ApiError'; this.status=status; this.detail=detail; }
}
const base = '/api/v1';
async function request(path, options={}) {
  let response;
  try {
    response = await fetch(`${base}${path}`, {credentials:'same-origin', ...options, headers:{Accept:'application/json', ...((options.method && options.method !== 'GET') ? {'X-Requested-With':'Travaux'} : {}), ...(options.body ? {'Content-Type':'application/json'} : {}), ...options.headers}});
  } catch { throw new ApiError('Le serveur est inaccessible. Vérifiez qu’il est démarré puis réessayez.',0); }
  if (response.status === 204) return null;
  const type = response.headers.get('content-type') || '';
  let payload;
  try { payload = type.includes('json') ? await response.json() : await response.text(); } catch { payload = null; }
  if (!response.ok) {
    const detail = payload?.detail || payload?.error || payload;
    const message = typeof detail === 'string' ? detail : detail?.message || (Array.isArray(detail) ? detail.map(item=>item.msg).join(' ; ') : null);
    throw new ApiError(message || (response.status===409 ? 'Cette version a changé. Rechargez les données avant de confirmer.' : response.status===401 ? 'Connectez-vous pour accéder à cet espace.' : 'L’opération n’a pas pu être effectuée. Réessayez.'),response.status,detail);
  }
  return payload;
}
