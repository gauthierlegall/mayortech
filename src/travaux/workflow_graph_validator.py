"""Graph validator and auto-repair engine for BPMN 2.0 workflows.

Ensures directed acyclic properties, reachability from start to end events,
and auto-repairs incomplete or ambiguous graphs generated by prompting.
"""

from __future__ import annotations

from collections import deque
from typing import Any, Dict, List, Set, Tuple


class WorkflowGraphValidator:
    """Validates structural and semantic rules of a BPMN graph."""

    @staticmethod
    def validate(nodes: List[Dict[str, Any]], edges: List[Dict[str, Any]]) -> Tuple[bool, List[str]]:
        errors = []
        node_ids = {n["id"] for n in nodes}

        # 1. Start event count
        start_nodes = [n for n in nodes if n.get("type") == "startEvent"]
        if len(start_nodes) != 1:
            errors.append(f"Le graphe doit avoir exactement 1 StartEvent (trouvé : {len(start_nodes)}).")

        # 2. End event count
        end_nodes = [n for n in nodes if n.get("type") == "endEvent"]
        if len(end_nodes) < 1:
            errors.append("Le graphe doit comporter au moins 1 EndEvent.")

        # 3. Valid edge references
        for e in edges:
            if e["sourceRef"] not in node_ids:
                errors.append(f"Arête {e.get('id')} : sourceRef '{e['sourceRef']}' inconnue.")
            if e["targetRef"] not in node_ids:
                errors.append(f"Arête {e.get('id')} : targetRef '{e['targetRef']}' inconnue.")

        # 4. Reachability from StartEvent
        if start_nodes:
            start_id = start_nodes[0]["id"]
            visited = set()
            queue = deque([start_id])
            adj: Dict[str, List[str]] = {nid: [] for nid in node_ids}
            for e in edges:
                if e["sourceRef"] in adj and e["targetRef"] in node_ids:
                    adj[e["sourceRef"]].append(e["targetRef"])

            while queue:
                curr = queue.popleft()
                if curr not in visited:
                    visited.add(curr)
                    for nxt in adj.get(curr, []):
                        if nxt not in visited:
                            queue.append(nxt)

            unreachable = node_ids - visited
            if unreachable:
                errors.append(f"Nœuds orphelins inatteignables depuis le départ : {', '.join(unreachable)}.")

            # Check if at least one EndEvent is reachable
            reachable_ends = [e["id"] for e in end_nodes if e["id"] in visited]
            if not reachable_ends:
                errors.append("Aucun EndEvent n'est atteignable depuis le StartEvent.")

        return len(errors) == 0, errors

    @staticmethod
    def auto_repair(
        nodes: List[Dict[str, Any]],
        edges: List[Dict[str, Any]],
    ) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
        """Automatically repairs broken, disconnected, or missing-end BPMN graphs."""
        repaired_nodes = [dict(n) for n in nodes]
        repaired_edges = [dict(e) for e in edges]
        node_ids = {n["id"] for n in repaired_nodes}

        # Ensure startEvent exists
        has_start = any(n.get("type") == "startEvent" for n in repaired_nodes)
        if not has_start:
            start_node = {"id": "start_auto", "type": "startEvent", "name": "Départ du processus", "x": 60, "y": 140}
            repaired_nodes.insert(0, start_node)
            node_ids.add("start_auto")
            if len(repaired_nodes) > 1:
                # Link to first non-start node
                first_target = repaired_nodes[1]["id"]
                repaired_edges.insert(0, {"id": "flow_start_auto", "sourceRef": "start_auto", "targetRef": first_target})

        # Ensure endEvent exists
        has_end = any(n.get("type") == "endEvent" for n in repaired_nodes)
        if not has_end:
            end_node = {"id": "end_auto", "type": "endEvent", "name": "Clôture du dossier", "x": 1000, "y": 140}
            repaired_nodes.append(end_node)
            node_ids.add("end_auto")

        # Find terminal nodes (nodes with 0 outgoing edges that are not endEvent)
        sources_with_outgoing = {e["sourceRef"] for e in repaired_edges}
        for n in repaired_nodes:
            if n.get("type") != "endEvent" and n["id"] not in sources_with_outgoing:
                # Find an endEvent to attach to
                target_end = next((en["id"] for en in repaired_nodes if en.get("type") == "endEvent"), "end_auto")
                repaired_edges.append({
                    "id": f"flow_auto_to_end_{n['id']}",
                    "sourceRef": n["id"],
                    "targetRef": target_end,
                })

        return repaired_nodes, repaired_edges
